import CoreVideo
import Foundation
import QuartzCore

/// A frame ready for display.
struct VideoFrame {
    let pixelBuffer: CVPixelBuffer
    /// Part of the buffer occupied by the image (from the top-left corner); the rest of the canvas is black background.
    let contentWidth: Int
    let contentHeight: Int
    /// Content instant shown in the frame (seconds, host clock — the same as `CACurrentMediaTime`):
    /// the arrival time of the source frame or, when generating, the smoothed game instant. Even spacing
    /// of these instants between consecutive on-screen frames means even motion.
    let captureTime: CFTimeInterval
    /// Time at which the frame should reach the screen. 0 = as soon as possible.
    let dueTime: CFTimeInterval
    /// `true` for a frame generated by interpolation.
    let isGenerated: Bool
    /// The deadline lies on the display refresh grid (one frame per refresh).
    var onDisplayGrid = false
}

enum FrameGenMode: String, CaseIterable, Identifiable, Codable {
    case off, auto, always
    var id: String { rawValue }

    var label: String {
        switch self {
        case .off: return String(localized: "Off")
        case .auto: return String(localized: "Auto")
        case .always: return String(localized: "Maximum")
        }
    }

    /// Compact label. The short "Off" uses an explicit key so it can be translated differently from `label`'s "Off".
    var shortLabel: String {
        switch self {
        case .off: return String(localized: "frameGen.shortLabel.off", defaultValue: "Off")
        case .auto: return String(localized: "Auto")
        case .always: return String(localized: "Max")
        }
    }

    var help: String {
        switch self {
        case .off: return String(localized: "No frame generation — lowest latency.")
        case .auto: return String(localized: "Generates frames up to the full display refresh rate when the game clearly falls short of it (below about 85%).")
        case .always: return String(localized: "Always generates frames when the game doesn't fill the display refresh rate — even at 50–55 fps.")
        }
    }
}

/// Resolution at which the image passes through the pipeline.
///
/// The VideoToolbox interpolator accepts only selected input sizes (verified on M3, macOS 27),
/// so we always capture into a fixed 16:9 "canvas" of one of them, and an image with a different
/// aspect ratio occupies its top-left part.
enum ProcessingResolution: Int, CaseIterable, Identifiable, Codable {
    case auto = 0, p1080 = 1080, p720 = 720, p576 = 576, p480 = 480
    var id: Int { rawValue }

    var label: String {
        switch self {
        case .auto: return String(localized: "Auto (up to 1080p)")
        case .p1080: return "1080p"
        case .p720: return "720p"
        case .p576: return "576p"
        case .p480: return "480p"
        }
    }

    /// Canvas size in pixels.
    var canvas: (width: Int, height: Int) {
        switch self {
        case .auto, .p1080: return (1920, 1080)
        case .p720: return (1280, 720)
        case .p576: return (1024, 576)
        case .p480: return (848, 480)
        }
    }

    /// For `auto`: the largest canvas that doesn't require upscaling the source.
    func resolved(contentPixelHeight: CGFloat) -> ProcessingResolution {
        guard self == .auto else { return self }
        if contentPixelHeight >= 1000 { return .p1080 }
        if contentPixelHeight >= 660 { return .p720 }
        if contentPixelHeight >= 530 { return .p576 }
        return .p480
    }
}

/// User settings. Changing `resolution` or `cropTitleBar` requires restarting capture;
/// the rest apply live.
struct EnhanceSettings: Equatable, Codable {
    var frameGen: FrameGenMode = .auto
    var dedupe = true
    var mlSuperRes = false
    var metalFX = true
    var sharpness: Float = 0.25
    var resolution: ProcessingResolution = .auto
    var cropTitleBar = true
    var showHUD = true
    /// Resolution of the console stream (built-in Remote Play): 1080, 720 or 540.
    var streamHeight = 1080
    /// H.265 stream instead of H.264.
    var streamHEVC = false
    /// Stream bitrate in Mbps requested from the console (chiaki-ng range: 2–100).
    var streamBitrateMbps = 100
    /// After clicking "Play" the window goes full screen.
    var autoFullScreen = true
    /// Test patterns and all windows in the source list.
    var showDiagnosticSources = false
    /// The console sees a DualSense controller (haptics, adaptive triggers, light bar).
    var dualSenseMode = true
    /// Vibration strength: 0 = off, 1 = normal, 2 = strong.
    var vibration: Float = 1
    var adaptiveTriggers = true
    /// Console audio volume (0…1) and mute.
    var volume: Float = 1
    var muted = false

    private static let key = "enhanceSettings.v2"

    init() {}

    /// Missing keys (saved by an older version) get default values instead of discarding everything.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let d = EnhanceSettings()
        frameGen = try c.decodeIfPresent(FrameGenMode.self, forKey: .frameGen) ?? d.frameGen
        dedupe = try c.decodeIfPresent(Bool.self, forKey: .dedupe) ?? d.dedupe
        mlSuperRes = try c.decodeIfPresent(Bool.self, forKey: .mlSuperRes) ?? d.mlSuperRes
        metalFX = try c.decodeIfPresent(Bool.self, forKey: .metalFX) ?? d.metalFX
        sharpness = try c.decodeIfPresent(Float.self, forKey: .sharpness) ?? d.sharpness
        resolution = try c.decodeIfPresent(ProcessingResolution.self, forKey: .resolution) ?? d.resolution
        cropTitleBar = try c.decodeIfPresent(Bool.self, forKey: .cropTitleBar) ?? d.cropTitleBar
        showHUD = try c.decodeIfPresent(Bool.self, forKey: .showHUD) ?? d.showHUD
        streamHeight = try c.decodeIfPresent(Int.self, forKey: .streamHeight) ?? d.streamHeight
        streamHEVC = try c.decodeIfPresent(Bool.self, forKey: .streamHEVC) ?? d.streamHEVC
        streamBitrateMbps = try c.decodeIfPresent(Int.self, forKey: .streamBitrateMbps) ?? d.streamBitrateMbps
        autoFullScreen = try c.decodeIfPresent(Bool.self, forKey: .autoFullScreen) ?? d.autoFullScreen
        showDiagnosticSources = try c.decodeIfPresent(Bool.self, forKey: .showDiagnosticSources) ?? d.showDiagnosticSources
        dualSenseMode = try c.decodeIfPresent(Bool.self, forKey: .dualSenseMode) ?? d.dualSenseMode
        vibration = try c.decodeIfPresent(Float.self, forKey: .vibration) ?? d.vibration
        adaptiveTriggers = try c.decodeIfPresent(Bool.self, forKey: .adaptiveTriggers) ?? d.adaptiveTriggers
        volume = try c.decodeIfPresent(Float.self, forKey: .volume) ?? d.volume
        muted = try c.decodeIfPresent(Bool.self, forKey: .muted) ?? d.muted
    }

    static func load() -> EnhanceSettings {
        guard let data = UserDefaults.standard.data(forKey: key),
              let value = try? JSONDecoder().decode(EnhanceSettings.self, from: data)
        else { return EnhanceSettings() }
        return value
    }

    func save() {
        if let data = try? JSONEncoder().encode(self) {
            UserDefaults.standard.set(data, forKey: Self.key)
        }
    }
}

enum FrameGeometry {
    /// Size of the image fitted into the canvas preserving aspect ratio; even dimensions (4:2:0 requirement).
    static func fit(content: CGSize, canvasWidth: Int, canvasHeight: Int) -> (width: Int, height: Int) {
        guard content.width >= 1, content.height >= 1 else { return (canvasWidth, canvasHeight) }
        let scale = min(Double(canvasWidth) / Double(content.width), Double(canvasHeight) / Double(content.height))
        let width = min(canvasWidth, Int((Double(content.width) * scale / 2).rounded()) * 2)
        let height = min(canvasHeight, Int((Double(content.height) * scale / 2).rounded()) * 2)
        return (max(2, width), max(2, height))
    }
}

/// Events-per-second counter that tolerates the source stopping.
struct RateMeter {
    private var count = 0
    private var windowStart: CFTimeInterval = 0
    private var lastTick: CFTimeInterval = 0
    private var rate = 0.0

    mutating func tick(_ now: CFTimeInterval = CACurrentMediaTime()) {
        if windowStart == 0 { windowStart = now }
        count += 1
        lastTick = now
        let elapsed = now - windowStart
        if elapsed >= 0.5 {
            rate = Double(count) / elapsed
            count = 0
            windowStart = now
        }
    }

    func value(_ now: CFTimeInterval = CACurrentMediaTime()) -> Double {
        now - lastTick > 1.0 ? 0 : rate
    }
}

final class Locked<Value>: @unchecked Sendable {
    private var value: Value
    private let lock = NSLock()

    init(_ value: Value) { self.value = value }

    func get() -> Value {
        lock.lock(); defer { lock.unlock() }
        return value
    }

    func set(_ newValue: Value) {
        lock.lock(); defer { lock.unlock() }
        value = newValue
    }

    @discardableResult
    func with<T>(_ body: (inout Value) -> T) -> T {
        lock.lock(); defer { lock.unlock() }
        return body(&value)
    }
}
