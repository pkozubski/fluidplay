#!/bin/zsh
# Builds a distributable release: dist/VeyraMac-<version>.dmg and dist/VeyraMac-<version>.zip.
# Usage: Scripts/release.sh
#
# Differences from Scripts/build.sh (local development):
#   - chiaki-ng's dependencies are linked statically from Homebrew archives (OpenSSL libcrypto,
#     Opus, json-c, miniupnpc, libevent) and libcurl comes from macOS, so the app runs on a Mac
#     without Homebrew. The only dylibs it loads are part of macOS.
#   - It is signed ad hoc unless a Developer ID identity is given. It is never signed with the
#     first identity in the keychain: an "Apple Development" certificate carries the developer's
#     e-mail address and is not meant for distribution.
#   - The hardened runtime is on (required for notarization; no entitlements are needed).
#   - It builds in build/release and never touches build/VeyraMac.app.
#
# Optional environment:
#   VEYRAMAC_RELEASE_IDENTITY  "Developer ID Application: ..." identity (name or SHA-1 hash).
#   VEYRAMAC_NOTARY_PROFILE    notarytool keychain profile, created beforehand with
#                              `xcrun notarytool store-credentials`. Needs VEYRAMAC_RELEASE_IDENTITY.
#                              The app and the DMG are notarized and stapled.
#
# Requires Scripts/build-chiaki.sh to have run, and the Homebrew packages listed in README.md
# (at build time only).
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$PWD"

die() { print -u2 -- "release.sh: $*"; exit 1; }
step() { print -- "\n==> $*"; }

# --- Configuration --------------------------------------------------------------------------------

# First value of a top-level setting in project.yml (`KEY: "value"`).
project_setting() {
  awk -F': *' -v key="$1" '$1 ~ "^[[:space:]]*" key "$" {
    sub(/[[:space:]]+#.*/, "", $2); gsub(/["[:space:]]/, "", $2); print $2; exit
  }' project.yml
}

VERSION="$(project_setting MARKETING_VERSION)"
TARGET="$(project_setting MACOSX_DEPLOYMENT_TARGET)"
[[ -n "$VERSION" ]] || die "MARKETING_VERSION not found in project.yml"
[[ -n "$TARGET" ]] || die "MACOSX_DEPLOYMENT_TARGET not found in project.yml"

IDENTITY="${VEYRAMAC_RELEASE_IDENTITY:-}"
NOTARY_PROFILE="${VEYRAMAC_NOTARY_PROFILE:-}"
[[ -z "$NOTARY_PROFILE" || -n "$IDENTITY" ]] \
  || die "VEYRAMAC_NOTARY_PROFILE needs VEYRAMAC_RELEASE_IDENTITY (notarization requires a Developer ID signature)"
if [[ -n "$IDENTITY" ]]; then
  identity_line="$(security find-identity -v -p codesigning | grep -F -- "$IDENTITY" | head -1 || true)"
  [[ -n "$identity_line" ]] || die "signing identity \"$IDENTITY\" not found in the keychain"
  [[ "$identity_line" == *'"Developer ID Application:'* ]] \
    || die "VEYRAMAC_RELEASE_IDENTITY must be a \"Developer ID Application\" identity"
fi

REL="build/release"
DERIVED="$REL/DerivedData"
APP="$REL/VeyraMac.app"
BIN="$APP/Contents/MacOS/VeyraMac"
DIST="dist"
NAME="VeyraMac-$VERSION"
ZIP="$DIST/$NAME.zip"
DMG="$DIST/$NAME.dmg"
BREW="$(brew --prefix)"
SDK="$(xcrun --sdk macosx --show-sdk-path)"
LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister

# Static archives replacing the Homebrew dylibs that build.sh links. libevent_core holds everything
# chiaki-ng uses from libevent. libcurl is not among them: chiaki-ng only calls curl, json-c,
# miniupnpc and libevent from its internet "holepunch" connection, which VeyraMac never starts
# (LAN only), and the system libcurl exports every function it references.
STATIC_LIBS=(
  "$BREW/opt/openssl@3/lib/libcrypto.a"
  "$BREW/opt/opus/lib/libopus.a"
  "$BREW/opt/json-c/lib/libjson-c.a"
  "$BREW/opt/miniupnpc/lib/libminiupnpc.a"
  "$BREW/opt/libevent/lib/libevent_core.a"
)
SYSTEM_CURL="$SDK/usr/lib/libcurl.tbd"

for lib in "${STATIC_LIBS[@]}" "$SYSTEM_CURL"; do
  [[ -f "$lib" ]] || die "missing $lib (see README.md for the Homebrew packages)"
done
[[ -f Vendor/build/chiaki/lib/libchiaki.a ]] || die "chiaki-ng is not built; run Scripts/build-chiaki.sh first"

print -- "VeyraMac $VERSION (deployment target macOS $TARGET)"
if [[ -n "$IDENTITY" ]]; then
  print -- "Signing: Developer ID${NOTARY_PROFILE:+, notarization with profile \"$NOTARY_PROFILE\"}"
else
  print -- "Signing: ad hoc (set VEYRAMAC_RELEASE_IDENTITY for a Developer ID signature)"
fi

# --- Build ----------------------------------------------------------------------------------------

step "Compiling the pipe2 shim"
# Homebrew's libevent.a targets macOS 27 and calls pipe2(), which libSystem has only since macOS 27;
# see Support/Compat/pipe2-compat.c.
mkdir -p "$REL/compat"
SHIM="$REL/compat/pipe2-compat.o"
xcrun clang -arch arm64 -mmacosx-version-min="$TARGET" -O2 -Wall -Wextra -Werror \
  -c Support/Compat/pipe2-compat.c -o "$SHIM"

# Settings passed with -xcconfig override the project's, for this build only.
XCCONFIG="$REL/Release.xcconfig"
{
  print -- "// Generated by Scripts/release.sh."
  print -rn -- "VEYRAMAC_THIRD_PARTY_LDFLAGS ="
  for lib in "${STATIC_LIBS[@]}" "$SYSTEM_CURL" "$ROOT/$SHIM"; do print -rn -- " \"$lib\""; done
  print
} > "$XCCONFIG"

step "Building (Release)"
xcodegen generate --quiet
LOG="$REL/xcodebuild.log"
if ! xcodebuild -project VeyraMac.xcodeproj -scheme VeyraMac -configuration Release \
    -derivedDataPath "$DERIVED" -destination 'platform=macOS,arch=arm64' \
    -xcconfig "$XCCONFIG" clean build > "$LOG" 2>&1; then
  grep -E "(^|: )error: |BUILD FAILED" "$LOG" | head -40 >&2 || true
  die "build failed (full log: $LOG)"
fi
# miniupnpc and libevent archives are built for a newer macOS than the target. ld warns about
# every object; the imports check below is what matters, so keep the rest of the output short.
grep -E "(^|: )warning: " "$LOG" | grep -v "was built for newer 'macOS' version" | sort -u || true
newer_objects=$(grep -c "was built for newer 'macOS' version" "$LOG" || true)
(( newer_objects == 0 )) || print -- "(ld: $newer_objects objects from static archives target a newer macOS; imports are checked below)"

BUILT="$DERIVED/Build/Products/Release/VeyraMac.app"
[[ -d "$BUILT" ]] || die "build product not found: $BUILT"
rm -rf "$APP"
ditto "$BUILT" "$APP"
# Keep only one registered copy per build, like build.sh does.
"$LSREGISTER" -u "$BUILT" 2>/dev/null || true
rm -rf "$BUILT"

built_version="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$APP/Contents/Info.plist")"
[[ "$built_version" == "$VERSION" ]] || die "Info.plist version $built_version differs from project.yml $VERSION"

step "Adding license texts"
# Binary redistribution requires the licenses of everything linked into the app.
LICENSES="$APP/Contents/Resources/Licenses"
mkdir -p "$LICENSES"
license() {
  [[ -f "$2" ]] || die "license file missing: $2"
  cp "$2" "$LICENSES/$1"
}
[[ -f LICENSE ]] && license VeyraMac-LICENSE.txt LICENSE
license chiaki-ng-AGPL-3.0-only-OpenSSL.txt Vendor/chiaki-ng/LICENSES/AGPL-3.0-only-OpenSSL.txt
license nanopb-LICENSE.txt Vendor/chiaki-ng/third-party/nanopb/LICENSE.txt
license jerasure-License.txt Vendor/chiaki-ng/third-party/jerasure/License.txt
license gf-complete-License.txt Vendor/chiaki-ng/third-party/gf-complete/License.txt
license OpenSSL-LICENSE.txt "$BREW/opt/openssl@3/LICENSE.txt"
license Opus-COPYING.txt "$BREW/opt/opus/COPYING"
license json-c-COPYING.txt "$BREW/opt/json-c/COPYING"
license miniupnpc-LICENSE.txt "$BREW/opt/miniupnpc/LICENSE"
license libevent-LICENSE.txt "$BREW/opt/libevent/LICENSE"
ls "$LICENSES"

# --- Checks ---------------------------------------------------------------------------------------

step "Checking linkage"
deps=("${(@f)$(otool -L "$BIN" | tail -n +2 | awk '{print $1}')}")
print -l -- "${deps[@]}"
for dep in "${deps[@]}"; do
  [[ "$dep" == /usr/lib/* || "$dep" == /System/Library/* ]] \
    || die "$BIN links $dep, which is not part of macOS"
done
if otool -l "$BIN" | grep -E "/opt/homebrew|/usr/local" >/dev/null; then
  die "load commands still mention Homebrew paths"
fi

minos="$(otool -l "$BIN" | awk '/LC_BUILD_VERSION/ {found = 1} found && $1 == "minos" {print $2; exit}')"
plist_min="$(/usr/libexec/PlistBuddy -c 'Print :LSMinimumSystemVersion' "$APP/Contents/Info.plist")"
print -- "Binary minos $minos, LSMinimumSystemVersion $plist_min"
[[ "$minos" == "$TARGET" ]] || die "binary minos $minos differs from the deployment target $TARGET"

# Code from static archives built for a newer macOS can import functions that older systems lack,
# and dyld refuses to launch the app when a non-weak import is missing. Compare the binary's
# non-weak imports with the C functions the SDK headers mark as introduced after the target.
target_major=${TARGET%%.*}
target_minor=${${TARGET#*.}%%.*}
newer=()
for (( v = target_minor + 1; v <= 9; v++ )); do newer+=("${target_major}[._]$v"); done
for (( v = target_major + 1; v <= target_major + 20; v++ )); do newer+=("$v([._][0-9]|\\))"); done
newer_re="${(j:|:)newer}"
grep -rhE -B1 -A1 "(macos|macosx)\\(($newer_re)|__MAC_($newer_re)" "$SDK/usr/include" 2>/dev/null \
  | grep -oE "[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\\(" | sed -E 's/[[:space:](]+$//' | sort -u \
  > "$REL/newer-functions.txt" || true
nm -m "$BIN" | awk '$1 == "(undefined)" && $2 == "external" {name = substr($3, 2); sub(/\$.*/, "", name); print name}' | sort -u \
  > "$REL/strong-imports.txt"
too_new=("${(@f)$(comm -12 "$REL/newer-functions.txt" "$REL/strong-imports.txt")}")
too_new=(${too_new:#})
(( ${#too_new} == 0 )) \
  || die "non-weak imports introduced after macOS $TARGET: ${too_new[*]} (the app would not launch on macOS $TARGET)"
print -- "No non-weak imports newer than macOS $TARGET ($(wc -l < "$REL/strong-imports.txt" | tr -d ' ') checked)"

# --- Signing --------------------------------------------------------------------------------------

step "Signing"
xattr -cr "$APP"
if [[ -n "$IDENTITY" ]]; then
  codesign --force --options runtime --timestamp --sign "$IDENTITY" "$APP"
else
  codesign --force --options runtime --sign - "$APP"
fi
codesign --verify --deep --strict --verbose=2 "$APP"
codesign -dv "$APP" 2>&1 | grep -E "^(Identifier|Format|CodeDirectory|Signature|TeamIdentifier|Runtime)" || true

# Submits a file to the notary service and waits for the verdict.
notarize() {
  local file="$1" result="$REL/notary-${1:t}.json" verdict id
  print -- "Submitting ${file:t} for notarization (this can take a few minutes)"
  xcrun notarytool submit "$file" --keychain-profile "$NOTARY_PROFILE" --wait --output-format json \
    > "$result" || true
  verdict="$(plutil -extract status raw -o - "$result" 2>/dev/null || echo unknown)"
  if [[ "$verdict" != "Accepted" ]]; then
    id="$(plutil -extract id raw -o - "$result" 2>/dev/null || true)"
    [[ -n "$id" ]] && print -u2 -- "Details: xcrun notarytool log $id --keychain-profile \"$NOTARY_PROFILE\""
    die "notarization of ${file:t} was not accepted (status: $verdict, response: $result)"
  fi
}

if [[ -n "$NOTARY_PROFILE" ]]; then
  step "Notarizing the app"
  ditto -c -k --keepParent "$APP" "$REL/notarize-app.zip"
  notarize "$REL/notarize-app.zip"
  rm -f "$REL/notarize-app.zip"
  xcrun stapler staple "$APP"
  xcrun stapler validate "$APP"
fi

# --- Packaging ------------------------------------------------------------------------------------

step "Packaging"
mkdir -p "$DIST"
rm -f "$ZIP" "$DMG"
ditto -c -k --sequesterRsrc --keepParent "$APP" "$ZIP"

DMG_ROOT="$REL/dmg"
rm -rf "$DMG_ROOT"
mkdir -p "$DMG_ROOT"
ditto "$APP" "$DMG_ROOT/VeyraMac.app"
ln -s /Applications "$DMG_ROOT/Applications"
hdiutil create -quiet -volname "VeyraMac $VERSION" -srcfolder "$DMG_ROOT" -ov -format UDZO "$DMG"
hdiutil verify -quiet "$DMG"
rm -rf "$DMG_ROOT"

if [[ -n "$IDENTITY" ]]; then
  codesign --force --timestamp --sign "$IDENTITY" "$DMG"
fi
if [[ -n "$NOTARY_PROFILE" ]]; then
  step "Notarizing the disk image"
  notarize "$DMG"
  xcrun stapler staple "$DMG"
  xcrun stapler validate "$DMG"
fi

step "Gatekeeper assessment"
spctl -a -vv "$APP" 2>&1 || true
if [[ -n "$IDENTITY" ]]; then
  spctl -a -vv -t open --context context:primary-signature "$DMG" 2>&1 || true
else
  print -- "(Ad hoc signatures are always rejected by Gatekeeper; users have to allow the app in"
  print -- " System Settings > Privacy & Security > Open Anyway.)"
fi
# The staged copy has the same bundle identifier as the developer's build/VeyraMac.app.
"$LSREGISTER" -u "$APP" 2>/dev/null || true

step "Done"
for file in "$DMG" "$ZIP"; do
  print -- "$file  $(du -h "$file" | cut -f1)  sha256 $(shasum -a 256 "$file" | cut -d' ' -f1)"
done
print -- "Minimum macOS: $minos (arm64)"
